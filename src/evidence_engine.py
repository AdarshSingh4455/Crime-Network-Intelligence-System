"""
evidence_engine.py
------------------
CNIS Phase 3H: Deterministic Evidence & Provenance Engine.

Compiles a mathematically grounded, fully traceable evidence layer connecting
every intelligence finding (entities, relationships, network metrics, anomalies,
temporal events, locations, and reports) to actual source records and deterministic
analytical transformations.

Answers the fundamental investigator question:
    "Why does CNIS show this?"

Strict Epistemic Principles:
  1. EvidenceClassification is distinct from EpistemicStatus.
  2. EpistemicStatus values: OBSERVED, DERIVED, SIGNAL, REVIEW_REQUIRED.
  3. Co-occurrence in source records is NOT proof of a criminal relationship.
  4. Anomaly signals are NOT proof of crime.
  5. Network centrality is NOT proof of guilt or hierarchy.
  6. Temporal proximity is NOT proof of coordination.
  7. Location overlap is NOT proof of a meeting.
  8. Raw source excerpts are 100% byte-for-byte verbatim from ingested records.
  9. Inverted indices provide average-case O(1) lookups.
  10. Zero external runtime LLM/API dependencies; 100% deterministic and idempotent.
"""

from __future__ import annotations
import re
from dataclasses import dataclass, field
from typing import Dict, List, Any, Optional, Tuple, Set


# ── 1. Epistemic Classifications & Statuses ───────────────────────────────────

class EvidenceClassification:
    """
    Categorizes the structural nature of an intelligence artifact.
    """
    SOURCE_RECORD = "SOURCE_RECORD"
    ENTITY_OBSERVATION = "ENTITY_OBSERVATION"
    RELATIONSHIP = "RELATIONSHIP"
    ANOMALY_SIGNAL = "ANOMALY_SIGNAL"
    NETWORK_METRIC = "NETWORK_METRIC"
    TEMPORAL_OBSERVATION = "TEMPORAL_OBSERVATION"
    LOCATION_OBSERVATION = "LOCATION_OBSERVATION"
    ENTITY_RESOLUTION = "ENTITY_RESOLUTION"

    ALL = {
        SOURCE_RECORD,
        ENTITY_OBSERVATION,
        RELATIONSHIP,
        ANOMALY_SIGNAL,
        NETWORK_METRIC,
        TEMPORAL_OBSERVATION,
        LOCATION_OBSERVATION,
        ENTITY_RESOLUTION,
    }


class EpistemicStatus:
    """
    Categorizes the epistemic foundation of an intelligence claim:
      - OBSERVED: Directly present in a source record.
      - DERIVED: Produced by deterministic mathematical/graph computation.
      - SIGNAL: Produced by an analytical detector (e.g. anomaly heuristics/models).
      - REVIEW_REQUIRED: Ambiguity detected requiring authorized human review.
    """
    OBSERVED = "OBSERVED"
    DERIVED = "DERIVED"
    SIGNAL = "SIGNAL"
    REVIEW_REQUIRED = "REVIEW_REQUIRED"

    ALL = {
        OBSERVED,
        DERIVED,
        SIGNAL,
        REVIEW_REQUIRED,
    }


